#!/usr/bin/env node
/**
 * Keeps components/ui/iconRegistry.ts in step with the icon names the app
 * actually uses.
 *
 * <Icon> used to look names up in lucide's `icons` barrel, which made Metro
 * bundle and evaluate all ~1,600 icons at startup. The registry imports only
 * the icons we use, one file each. A name missing from it renders an empty
 * box, so this script is the guard:
 *
 *   node scripts/icons-registry.js           check; exit 1 if a used name is missing
 *   node scripts/icons-registry.js --write   regenerate the registry from the code
 *
 * It also writes iconGlyphs.ts: each icon's character in lucide's icon font
 * (assets/fonts/lucide.ttf, lucide-static's font for the same lucide version,
 * with its name -> code point map beside it). Android draws plain icons as that
 * glyph. When lucide-react-native is upgraded, replace lucide.ttf and
 * lucide.codepoints.json from `npm pack lucide-static@<same version>`
 * (package/font/lucide.ttf and package/font/info.json); the check fails until
 * the two versions match, so a glyph can never disagree with its SVG.
 *
 * "Used" is deliberately broad: any quoted string anywhere in app code that
 * is exactly a lucide icon name. Icon names travel through config arrays,
 * ternaries and props, so matching only `name="..."` misses real ones. The
 * cost is the odd extra icon (a screen called "Settings" pulls in the gear),
 * which is a few hundred bytes each.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const REGISTRY = path.join(ROOT, "components", "ui", "iconRegistry.ts");
const PATHS = path.join(ROOT, "components", "ui", "iconPaths.ts");
const GLYPHS = path.join(ROOT, "components", "ui", "iconGlyphs.ts");
const FONT_CODES = path.join(ROOT, "assets", "fonts", "lucide.codepoints.json");
const LUCIDE_INDEX = path.join(
  ROOT,
  "node_modules",
  "lucide-react-native",
  "dist",
  "esm",
  "icons",
  "index.js",
);
const IMPORT_BASE = "lucide-react-native/dist/esm/icons/";

// Same exclusions as tsconfig, plus things that are not app code.
const SKIP_DIRS = new Set([
  "node_modules",
  "android",
  "ios",
  ".git",
  ".expo",
  ".github",
  "__tests__",
  "__mocks__",
  "scripts",
  "coverage",
  "dist",
  "build",
  "public",
  "assets",
  "docs",
  "dehub-stream-backend",
  "cosmic-echo-hero",
]);
const SKIP_PATHS = new Set(["components/messages", "components/ui/iconRegistry.ts"]);

/** Canonical lucide name -> file slug, e.g. CircleAlert -> circle-alert. */
function loadLucideNames() {
  const src = fs.readFileSync(LUCIDE_INDEX, "utf8");
  const map = new Map();
  for (const m of src.matchAll(/default as (\w+) \} from '\.\/([\w-]+)\.js'/g)) {
    map.set(m[1], m[2]);
  }
  if (map.size < 1000) {
    throw new Error(`Parsed only ${map.size} icons from ${LUCIDE_INDEX}; has its format changed?`);
  }
  return map;
}

function walk(dir, out) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    const rel = path.relative(ROOT, full).split(path.sep).join("/");
    if (SKIP_PATHS.has(rel)) continue;
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) walk(full, out);
    } else if (/\.(tsx?|jsx?)$/.test(entry.name) && !entry.name.endsWith(".d.ts")) {
      out.push(full);
    }
  }
  return out;
}

/** Icon name -> files that mention it. */
function findUsedNames(lucide) {
  const used = new Map();
  for (const file of walk(ROOT, [])) {
    const src = fs.readFileSync(file, "utf8");
    for (const m of src.matchAll(/['"`]([A-Z][A-Za-z0-9]*)['"`]/g)) {
      if (!lucide.has(m[1])) continue;
      if (!used.has(m[1])) used.set(m[1], new Set());
      used.get(m[1]).add(path.relative(ROOT, file).split(path.sep).join("/"));
    }
  }
  return used;
}

function readRegisteredNames() {
  if (!fs.existsSync(REGISTRY)) return new Set();
  const src = fs.readFileSync(REGISTRY, "utf8");
  return new Set([...src.matchAll(/^ {2}(\w+): \w+Icon,\r?$/gm)].map((m) => m[1]));
}

function renderRegistry(names, lucide) {
  const sorted = [...names].sort();
  const lines = [
    "// Generated by scripts/icons-registry.js (`npm run icons:write`). Do not edit by hand.",
    "//",
    "// Only these icons are bundled. Importing each icon's own file, rather than",
    "// anything from the package root, keeps the other ~1,600 out of the bundle.",
    'import type { LucideIcon } from "lucide-react-native";',
    // `Icon` suffix so names like Map, Image and Text do not shadow globals.
    ...sorted.map((n) => `import ${n}Icon from "${IMPORT_BASE}${lucide.get(n)}";`),
    "",
    "export const iconRegistry = {",
    ...sorted.map((n) => `  ${n}: ${n}Icon,`),
    "} satisfies Record<string, LucideIcon>;",
    "",
    "export type IconName = keyof typeof iconRegistry;",
    "",
  ];
  return lines.join("\n");
}

/**
 * Each icon's shapes merged into one path. react-native-svg mounts a native
 * view per element, so a four-shape icon was six views (Svg, its group, four
 * shapes) and a feed card's action row alone ran to dozens. One path strokes
 * identically with round caps and joins; icons whose shapes set their own
 * attributes (a filled dot) are left out and keep lucide's renderer.
 */
const NUMBER = /-?(?:\d+\.?\d*|\.\d+)(?:e[-+]?\d+)?/gi;
const GEOMETRY = new Set(["key", "d", "cx", "cy", "r", "rx", "ry", "x", "y", "width", "height", "x1", "y1", "x2", "y2", "points"]);

function fmt(n) {
  return String(Math.round(n * 1000) / 1000);
}

/** Joined after another shape, a leading relative moveto would no longer be absolute. */
function absoluteStart(d) {
  const t = d.trim();
  if (t[0] !== "m") return t;
  const m = t.match(/^m([^A-Za-z]*)([\s\S]*)$/);
  const [x, y, ...rest] = m[1].match(NUMBER) || [];
  return `M${x} ${y}${rest.length ? `l${rest.join(" ")}` : ""}${m[2]}`;
}

function shapeToPath(tag, a) {
  switch (tag) {
    case "path":
      return absoluteStart(a.d);
    case "circle":
    case "ellipse": {
      const cx = Number(a.cx);
      const cy = Number(a.cy);
      const rx = Number(a.r ?? a.rx);
      const ry = Number(a.r ?? a.ry);
      const arc = (dx) => `a${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(dx)} 0`;
      return `M${fmt(cx - rx)} ${fmt(cy)}${arc(2 * rx)}${arc(-2 * rx)}Z`;
    }
    case "rect": {
      const x = Number(a.x || 0);
      const y = Number(a.y || 0);
      const w = Number(a.width);
      const h = Number(a.height);
      const rx = Math.min(Number(a.rx ?? a.ry ?? 0), w / 2);
      const ry = Math.min(Number(a.ry ?? a.rx ?? 0), h / 2);
      if (!rx || !ry) return `M${fmt(x)} ${fmt(y)}h${fmt(w)}v${fmt(h)}h${fmt(-w)}Z`;
      const arc = (dx, dy) => `a${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(dx)} ${fmt(dy)}`;
      return (
        `M${fmt(x + rx)} ${fmt(y)}h${fmt(w - 2 * rx)}${arc(rx, ry)}v${fmt(h - 2 * ry)}${arc(-rx, ry)}` +
        `h${fmt(2 * rx - w)}${arc(-rx, -ry)}v${fmt(2 * ry - h)}${arc(rx, -ry)}Z`
      );
    }
    case "line":
      return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case "polyline":
    case "polygon": {
      const pts = String(a.points).match(NUMBER);
      let d = `M${pts[0]} ${pts[1]}`;
      for (let i = 2; i < pts.length; i += 2) d += `L${pts[i]} ${pts[i + 1]}`;
      return tag === "polygon" ? `${d}Z` : d;
    }
    default:
      return null;
  }
}

function mergedPath(slug) {
  const src = fs.readFileSync(path.join(path.dirname(LUCIDE_INDEX), `${slug}.js`), "utf8");
  const m = src.match(/createLucideIcon\("\w+", (\[[\s\S]*\])\);/);
  if (!m) return null;
  const node = Function(`"use strict"; return (${m[1]});`)();
  const parts = [];
  for (const [tag, attrs] of node) {
    if (Object.keys(attrs).some((k) => !GEOMETRY.has(k))) return null;
    const d = shapeToPath(tag, attrs);
    if (!d) return null;
    parts.push(d);
  }
  return [parts.join(""), node.length];
}

function renderPaths(names, lucide) {
  const lines = [
    "// Generated by scripts/icons-registry.js (`npm run icons:write`). Do not edit by hand.",
    "//",
    "// Each icon's shapes merged into one SVG path, which <Icon> draws as a single",
    "// native shape instead of a view per shape. Entries are [path, shape count].",
    "export const iconPaths: Partial<Record<string, readonly [string, number]>> = {",
  ];
  for (const n of [...names].sort()) {
    const merged = mergedPath(lucide.get(n));
    if (merged) lines.push(`  ${n}: [${JSON.stringify(merged[0])}, ${merged[1]}],`);
  }
  lines.push("};", "");
  return lines.join("\n");
}

/** lucide slug -> font code point, refusing a font from another lucide version. */
function loadGlyphCodes() {
  const { version, codes } = JSON.parse(fs.readFileSync(FONT_CODES, "utf8"));
  const svgVersion = require(path.join(ROOT, "node_modules", "lucide-react-native", "package.json")).version;
  if (version !== svgVersion) {
    console.error(
      `assets/fonts/lucide.ttf is lucide ${version} but lucide-react-native is ${svgVersion}. ` +
        "Replace lucide.ttf and lucide.codepoints.json from lucide-static at the same version.",
    );
    process.exit(1);
  }
  return codes;
}

function renderGlyphs(names, lucide, codes) {
  const lines = [
    "// Generated by scripts/icons-registry.js (`npm run icons:write`). Do not edit by hand.",
    "//",
    "// Each icon's character in lucide's icon font (assets/fonts/lucide.ttf), which",
    "// <Icon> draws as one text glyph on Android instead of an SVG.",
    "export const iconGlyphs: Partial<Record<string, string>> = {",
  ];
  for (const n of [...names].sort()) {
    const code = codes[lucide.get(n)];
    if (code) lines.push(`  ${n}: "\\u${code}",`);
  }
  lines.push("};", "");
  return lines.join("\n");
}

function main() {
  const lucide = loadLucideNames();
  const used = findUsedNames(lucide);
  const codes = loadGlyphCodes();

  if (process.argv.includes("--write")) {
    fs.writeFileSync(REGISTRY, renderRegistry(used.keys(), lucide));
    fs.writeFileSync(PATHS, renderPaths(used.keys(), lucide));
    fs.writeFileSync(GLYPHS, renderGlyphs(used.keys(), lucide, codes));
    console.log(`Wrote ${path.relative(ROOT, REGISTRY)} with ${used.size} icons.`);
    return;
  }

  const registered = readRegisteredNames();
  const missing = [...used.keys()].filter((n) => !registered.has(n)).sort();
  const unused = [...registered].filter((n) => !used.has(n)).sort();

  if (unused.length) {
    console.log(`Registered but no longer referenced (safe to drop with --write): ${unused.join(", ")}`);
  }
  const pathsOnDisk = fs.existsSync(PATHS) ? fs.readFileSync(PATHS, "utf8").replace(/\r\n/g, "\n") : "";
  if (pathsOnDisk !== renderPaths(registered, lucide)) {
    console.error("components/ui/iconPaths.ts is out of date. Run `npm run icons:write` and commit the result.");
    process.exit(1);
  }
  const glyphsOnDisk = fs.existsSync(GLYPHS) ? fs.readFileSync(GLYPHS, "utf8").replace(/\r\n/g, "\n") : "";
  if (glyphsOnDisk !== renderGlyphs(registered, lucide, codes)) {
    console.error("components/ui/iconGlyphs.ts is out of date. Run `npm run icons:write` and commit the result.");
    process.exit(1);
  }
  if (missing.length) {
    console.error("Icon names used in the app but missing from components/ui/iconRegistry.ts:");
    for (const n of missing) console.error(`  ${n}  (${[...used.get(n)].slice(0, 3).join(", ")})`);
    console.error("They would render as empty boxes. Run `npm run icons:write` and commit the result.");
    process.exit(1);
  }
  console.log(`Icon registry OK: ${registered.size} icons registered, ${used.size} referenced.`);
}

main();
