#!/usr/bin/env python3
"""Build assets/fonts/cut-icons.ttf and components/ui/cutIconGlyphs.ts.

The cut icons (components/ui/cut-icons.tsx) are SVG artwork. On Android every
SvgView is painted in software into its own bitmap on the UI thread and
uploaded as a new texture each time it mounts, and a feed post carries about
ten of them. As glyphs of a font they are one Text each, drawn from the GPU
glyph atlas, like the lucide icons already are (libs/iconFont.ts).

Input: assets/fonts/cut-icons.sources.json, written by
  CUT_ICONS_WRITE=1 npx jest __tests__/components/cutIconFont.test.tsx
Needs: pip install picosvg fonttools skia-pathops

Same metrics as lucide.ttf: 1000 units per em, ascent 1000, descent 0, every
glyph 1000 wide, so <Icon>'s glyph style places both fonts the same way. The
artwork's 32-unit box maps onto the em 1:1.
"""
import hashlib
import json
import os
import sys

import pathops
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from picosvg.svg import SVG
from picosvg.svg_pathops import skia_path

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SOURCES = os.path.join(ROOT, "assets", "fonts", "cut-icons.sources.json")
FONT = os.path.join(ROOT, "assets", "fonts", "cut-icons.ttf")
GLYPHS_TS = os.path.join(ROOT, "components", "ui", "cutIconGlyphs.ts")

FAMILY = "CutIcons"
UPEM = 1000
BOX = 32.0
FIRST_CODEPOINT = 0xE000


def outline(markup):
    """One filled outline for the whole drawing, or None if it can't be one.

    A mask (a cut-out drawn in black) can't be flattened by picosvg, and those
    icons stay SVG.
    """
    if "<mask" in markup:
        return None
    pico = SVG.fromstring(markup).topicosvg()
    paths = []
    for shape in pico.shapes():
        paths.append(skia_path(shape.as_cmd_seq(), shape.fill_rule))
    if not paths:
        return None
    # Pairwise, not OpBuilder: OpBuilder dropped a stroked ring's inner
    # contour and filled the shape in.
    merged = pathops.Path()
    for p in paths:
        merged = pathops.op(merged, p, pathops.PathOp.UNION, fix_winding=True, keep_starting_points=False)
    return merged


def glyph_for(path):
    pen = TTGlyphPen(None)
    scale = UPEM / BOX
    # SVG y runs down from the top; font y runs up from the baseline, and the
    # em's top is the ascent (1000).
    transform = TransformPen(Cu2QuPen(pen, max_err=0.5, reverse_direction=True), (scale, 0, 0, -scale, 0, UPEM))
    path.draw(transform)
    return pen.glyph()


def main():
    with open(SOURCES, encoding="utf8") as f:
        data = json.load(f)
    names, sources = data["names"], data["sources"]

    glyph_order = [".notdef"]
    glyphs = {".notdef": TTGlyphPen(None).glyph()}
    cmap = {}
    chars = {}  # source key -> {"o": cp, "f": cp}
    skipped = []
    cp = FIRST_CODEPOINT
    for key in sorted(sources):
        entry = {}
        for variant, tag in (("outline", "o"), ("filled", "f")):
            markup = sources[key].get(variant)
            if markup is None:
                continue
            path = outline(markup)
            if path is None:
                skipped.append(f"{key}.{variant}")
                continue
            gname = f"cut_{key}" + ("_fill" if tag == "f" else "")
            glyph_order.append(gname)
            glyphs[gname] = glyph_for(path)
            cmap[cp] = gname
            entry[tag] = cp
            cp += 1
        if "o" in entry:
            chars[key] = entry

    fb = FontBuilder(UPEM, isTTF=True)
    fb.setupGlyphOrder(glyph_order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics({g: (UPEM, glyphs[g].xMin if hasattr(glyphs[g], "xMin") else 0) for g in glyph_order})
    fb.setupHorizontalHeader(ascent=UPEM, descent=0, lineGap=0)
    fb.setupNameTable({"familyName": FAMILY, "styleName": "Regular"})
    # Vertical metrics copied from lucide.ttf (typo metrics on, as there), so
    # Android lays out both icon fonts identically.
    fb.setupOS2(
        sTypoAscender=UPEM, sTypoDescender=0, sTypoLineGap=90,
        usWinAscent=1090, usWinDescent=6, fsSelection=0xC0, achVendID="RFTN", version=4,
    )
    fb.setupPost()
    fb.setupMaxp()
    # Deterministic output: the same sources build the same file.
    fb.font["head"].created = fb.font["head"].modified = 0
    fb.save(FONT)

    with open(SOURCES, "rb") as f:
        digest = hashlib.sha1(f.read()).hexdigest()[:12]
    lines = [
        "// Generated by scripts/build-cut-icon-font.py. Do not edit by hand.",
        "//",
        "// Each cut icon's character in assets/fonts/cut-icons.ttf, which <Icon>",
        "// draws as one text glyph on Android instead of an SVG: `o` is the icon as",
        "// drawn with no fill, `f` with its fill set to the icon's own colour.",
        f'export const CUT_ICON_SOURCES = "{digest}";',
        "",
        "export const cutIconGlyphs: Partial<Record<string, { o: string; f?: string }>> = {",
    ]
    for name in sorted(names):
        entry = chars.get(names[name])
        if not entry:
            continue
        parts = [f'o: "\\u{entry["o"]:04x}"']
        if "f" in entry:
            parts.append(f'f: "\\u{entry["f"]:04x}"')
        lines.append(f"  {name}: {{ {', '.join(parts)} }},")
    lines.append("};")
    with open(GLYPHS_TS, "w", encoding="utf8") as f:
        f.write("\n".join(lines) + "\n")

    print(f"{len(glyph_order) - 1} glyphs, {len(chars)} icons, skipped: {', '.join(skipped) or 'none'}")


if __name__ == "__main__":
    sys.exit(main())
